/** Pins the existing five-table DDL with validate; no level/draw/wallet expansion. */
class LegacyKeycapEconomyStorageTest {
    private static StandardServiceRegistry registry;
    private static SessionFactory factory;
    private static java.sql.Connection schemaConnection;
    private static final Instant ACQUIRED = Instant.parse("2026-09-01T00:00:00Z");

    @BeforeAll static void startAgainstLegacySchema() throws Exception {
        String url = "jdbc:h2:mem:economy_" + UUID.randomUUID() + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1";
        String ddl = """
            create table app_user (id uuid primary key, status varchar(20) not null,
                nickname text, nickname_normalized text, profile_image_url text,
                onboarding_reward_claimed boolean not null, onboarding_completed_at timestamp with time zone,
                last_login_at timestamp with time zone, withdrawn_at timestamp with time zone,
                created_at timestamp with time zone not null, updated_at timestamp with time zone not null);
            create table keycap (id bigint generated by default as identity primary key, public_id uuid not null unique,
                code varchar(60) not null unique, name varchar(80) not null, grade varchar(20) not null,
                required_shard_count integer not null, season integer not null, acquisition_type varchar(20) not null,
                image_url text, sound_url text, sort_order integer not null, active boolean not null,
                created_at timestamp with time zone not null, updated_at timestamp with time zone not null);
            create table user_keycap (id bigint generated by default as identity primary key, public_id uuid not null unique,
                user_id uuid not null references app_user(id), keycap_id bigint not null references keycap(id),
                shard_count integer not null, status varchar(20) not null check(status in ('IN_PROGRESS','COMPLETED')),
                equipped boolean not null, completed_at timestamp with time zone,
                created_at timestamp with time zone not null, updated_at timestamp with time zone not null,
                constraint uq_user_keycap_user_keycap unique(user_id,keycap_id));
            create table keycap_box_account (id bigint generated by default as identity primary key, public_id uuid not null unique,
                user_id uuid not null unique references app_user(id), box_balance integer not null,
                free_open_used_count integer not null, ad_open_used_count integer not null,
                open_cycle_started_at timestamp with time zone not null, version bigint not null,
                created_at timestamp with time zone not null, updated_at timestamp with time zone not null);
            create table keycap_box_open (id bigint generated by default as identity primary key, public_id uuid not null unique,
                user_id uuid not null references app_user(id), keycap_id bigint not null references keycap(id),
                open_method varchar(30) not null check(open_method in ('FREE','ADVERTISEMENT','BULK_REWARD')),
                shard_count integer not null, idempotency_key varchar(100) not null, request_hash varchar(255) not null,
                ad_reward_id varchar(255), completed boolean not null, opened_at timestamp with time zone not null,
                created_at timestamp with time zone not null, updated_at timestamp with time zone not null,
                constraint uq_keycap_box_open_user_idempotency unique(user_id,idempotency_key));
            """;
        schemaConnection = DriverManager.getConnection(url, "sa", "");
        try (var statement = schemaConnection.createStatement()) {
            for (String sql : ddl.split(";")) if (!sql.isBlank()) statement.execute(sql);
        }
        registry = new StandardServiceRegistryBuilder()
                .applySetting("hibernate.connection.driver_class", "org.h2.Driver")
                .applySetting("hibernate.connection.url", url).applySetting("hibernate.connection.username", "sa")
                .applySetting("hibernate.connection.password", "")
                .applySetting("hibernate.hbm2ddl.auto", "validate").build();
        factory = new MetadataSources(registry).addAnnotatedClass(AppUser.class).addAnnotatedClass(Keycap.class)
                .addAnnotatedClass(UserKeycap.class).addAnnotatedClass(KeycapBoxAccount.class)
                .addAnnotatedClass(KeycapBoxOpen.class).buildMetadata().buildSessionFactory();
    }

    @AfterAll static void close() throws Exception {
        if (factory != null) factory.close();
        if (registry != null) StandardServiceRegistryBuilder.destroy(registry);
        if (schemaConnection != null) schemaConnection.close();
    }

    @Test void legacyProgressMovesOnceAndExistingCompletedKeycapKeepsItsDateAndLevel() {
        try (Session session = factory.openSession()) {
            var tx = session.beginTransaction();
            AppUser user = AppUser.createActive("legacy", null); session.persist(user);
            Keycap first = keycap("first"); session.persist(first);
            Keycap second = keycap("second"); session.persist(second);
            KeycapBoxAccount wallet = KeycapBoxAccount.createFor(user, ACQUIRED); wallet.addBoxes(9); session.persist(wallet);
            UserKeycap owned = UserKeycap.createCompletedOnboardingReward(user, first, ACQUIRED); session.persist(owned);
            UserKeycap pending = UserKeycap.createInProgress(user, second); pending.addShard(3, ACQUIRED); session.persist(pending);
            session.flush();
            var repos = new JpaRepositoryFactory(session);
            var users = repos.getRepository(AppUserRepository.class);
            var keys = repos.getRepository(UserKeycapRepository.class);
            var wallets = repos.getRepository(KeycapBoxAccountRepository.class);
            var service = new KeycapBoxAccountService(wallets, keys);
            assertThat(service.getAvailableShardBalance(user.getId())).isEqualTo(12);
            assertThat(wallet.getBoxBalance()).isEqualTo(9);
            new UserRewardLock(users).acquire(user.getId());
            assertThat(service.getForUserForUpdate(user.getId()).getShardBalance()).isEqualTo(12);
            assertThat(keys.sumLegacyShardCount(user.getId())).isZero();
            wallet.consumeShards(5); wallet.addShards(2); owned.levelUp();
            assertThat(service.getForUserForUpdate(user.getId()).getShardBalance()).isEqualTo(9);
            assertThat(owned.getLevel()).isEqualTo(2);
            assertThat(owned.getCompletedAt()).isEqualTo(ACQUIRED);
            tx.commit();
            session.clear();
            assertThat(wallets.findByUserId(user.getId()).orElseThrow().getShardBalance()).isEqualTo(9);
            assertThat(keys.findByPublicId(owned.getPublicId()).orElseThrow().getLevel()).isEqualTo(2);
        }
    }

    @Test void drawReceiptUsesExistingAuditAndDoesNotPolluteOldHistory() {
        try (Session session = factory.openSession()) {
            var tx = session.beginTransaction();
            AppUser user = AppUser.createActive("receipt", null); session.persist(user);
            Keycap keycap = keycap("receipt"); session.persist(keycap);
            var repos = new JpaRepositoryFactory(session);
            var opens = repos.getRepository(KeycapBoxOpenRepository.class);
            opens.save(KeycapBoxOpen.createFor(user, KeycapBoxOpen.OpenMethod.FREE, keycap, 2,
                    "legacy-key", "legacy-hash", null, true, ACQUIRED));
            var draws = new KeycapDrawRepository(opens, new ObjectMapper());
            String rawKey = "키".repeat(100);
            KeycapDraw draw = draws.save(KeycapDraw.createFor(user, keycap, 5, 8, false, rawKey, ACQUIRED));
            session.flush(); session.clear();
            var replay = draws.findByUserIdAndIdempotencyKeyWithKeycap(user.getId(), rawKey).orElseThrow();
            assertThat(replay.getPublicId()).isEqualTo(draw.getPublicId());
            assertThat(replay.getLevelAfter()).isEqualTo(8);
            assertThat(replay.getShardsSpent()).isEqualTo(5);
            assertThat(replay.isNewlyAcquired()).isFalse();
            assertThat(opens.findHistoryByUserId(user.getId(), null, null, PageRequest.of(0, 10)))
                    .extracting(KeycapBoxOpen::getIdempotencyKey).containsExactly("legacy-key");
            tx.commit();
        }
    }

    @Test void failedTransactionRestoresWalletAndPendingShards() {
        UUID userId;
        try (Session session = factory.openSession()) {
            var tx = session.beginTransaction();
            AppUser user = AppUser.createActive("rollback", null); session.persist(user); userId = user.getId();
            Keycap keycap = keycap("rollback"); session.persist(keycap);
            KeycapBoxAccount wallet = KeycapBoxAccount.createFor(user, ACQUIRED); wallet.addBoxes(9); session.persist(wallet);
            UserKeycap pending = UserKeycap.createInProgress(user, keycap); pending.addShard(3, ACQUIRED); session.persist(pending);
            tx.commit();
        }
        try (Session session = factory.openSession()) {
            var tx = session.beginTransaction();
            var repos = new JpaRepositoryFactory(session);
            new UserRewardLock(repos.getRepository(AppUserRepository.class)).acquire(userId);
            var service = new KeycapBoxAccountService(repos.getRepository(KeycapBoxAccountRepository.class),
                    repos.getRepository(UserKeycapRepository.class));
            assertThat(service.getForUserForUpdate(userId).getShardBalance()).isEqualTo(12);
            session.flush(); tx.rollback();
        }
        try (Session session = factory.openSession()) {
            var repos = new JpaRepositoryFactory(session);
            assertThat(repos.getRepository(KeycapBoxAccountRepository.class).findByUserId(userId).orElseThrow().getShardBalance()).isEqualTo(9);
            assertThat(repos.getRepository(UserKeycapRepository.class).sumLegacyShardCount(userId)).isEqualTo(3);
        }
    }

    private static Keycap keycap(String prefix) {
        return Keycap.createFor(prefix + UUID.randomUUID(), prefix, Keycap.Grade.COMMON, 20, 1, null, null, 1);
    }
}
