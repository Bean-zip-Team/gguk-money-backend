-- BEA-390: 조각 지급·사용 원장.
-- 운영은 ddl-auto=validate 라 이 테이블이 없으면 새 버전이 뜨지 않는다. 배포 **전에** 적용한다.
-- 다시 실행해도 안전하다(IF NOT EXISTS). 이 테이블을 모르는 이전 버전은 영향을 받지 않으므로
-- 배포를 되돌려도 그대로 두면 된다.
--
-- 친구 기능보다 먼저 배포해서 출시 전 조각 발행량(가드레일 기준값)을 쌓는다.
BEGIN;

SET LOCAL lock_timeout = '3s';
SET LOCAL statement_timeout = '30s';

CREATE TABLE IF NOT EXISTS shard_ledger (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       UUID        NOT NULL,
    delta         INTEGER     NOT NULL,
    reason        VARCHAR(40) NOT NULL,
    ref_id        VARCHAR(128),
    balance_after INTEGER     NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_shard_ledger_delta CHECK (delta <> 0)
);

-- 사용자별 이력 조회와 하루 발행량 집계에 쓴다.
CREATE INDEX IF NOT EXISTS ix_shard_ledger_user_created ON shard_ledger (user_id, created_at);
CREATE INDEX IF NOT EXISTS ix_shard_ledger_created_reason ON shard_ledger (created_at, reason);

COMMIT;

