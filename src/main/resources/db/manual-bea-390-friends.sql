-- BEA-390: 친구 초대·응원 테이블.
-- 운영은 ddl-auto=validate 라 이 테이블들이 없으면 새 버전이 뜨지 않는다. 배포 **전에** 적용한다.
-- develop 에 머지하면 알파에 바로 배포되므로 알파 DB 에는 머지 전에 적용한다.
-- 다시 실행해도 안전하다(IF NOT EXISTS). 이 테이블들을 모르는 이전 버전은 영향을 받지 않으므로
-- 배포를 되돌려도 그대로 두면 된다.
--
-- 같이 적용할 것: manual-bea-390-shard-ledger.sql, manual-notification-type-check.sql
BEGIN;

SET LOCAL lock_timeout = '3s';
SET LOCAL statement_timeout = '30s';

-- 초대 코드. 한 사람에 하나이고 바뀌지 않는다.
CREATE TABLE IF NOT EXISTS invite_code (
    user_id    UUID        PRIMARY KEY,
    code       VARCHAR(8)  NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_invite_code_code UNIQUE (code)
);

-- 친구 관계. 두 사람에 한 행이고 ID 가 작은 쪽이 user_low 다.
CREATE TABLE IF NOT EXISTS friendship (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_low   UUID        NOT NULL,
    user_high  UUID        NOT NULL,
    source     VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_friendship_pair UNIQUE (user_low, user_high),
    CONSTRAINT ck_friendship_order CHECK (user_low < user_high)
);

-- user_low 쪽 조회는 유니크 제약의 인덱스가 맡는다.
CREATE INDEX IF NOT EXISTS ix_friendship_user_high ON friendship (user_high);

-- 초대. 링크로 앱이 열리면 PENDING, 새로 가입하면 SUCCESS. 만료는 없다.
-- (inviter_id, visit_key) 유니크는 visit_key 가 NULL 인 행끼리는 겹치지 않는다(방문 기록 없이 가입한 건).
CREATE TABLE IF NOT EXISTS invite (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id        UUID        NOT NULL,
    inviter_id       UUID        NOT NULL,
    invitee_id       UUID,
    visit_key        UUID,
    status           VARCHAR(20) NOT NULL,
    created_at       TIMESTAMPTZ NOT NULL,
    succeeded_at     TIMESTAMPTZ,
    inviter_acked_at TIMESTAMPTZ,
    CONSTRAINT uq_invite_public_id UNIQUE (public_id),
    CONSTRAINT uq_invite_invitee UNIQUE (invitee_id),
    CONSTRAINT uq_invite_inviter_visit UNIQUE (inviter_id, visit_key)
);

CREATE INDEX IF NOT EXISTS ix_invite_inviter_status ON invite (inviter_id, status);

-- 응원. 하루 응원 수와 같은 친구 하루 한 번을 이 테이블로 판정한다.
-- read_at 과 reward_shards 는 받는 사람이 확인할 때 채워진다.
CREATE TABLE IF NOT EXISTS cheer (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id          UUID        NOT NULL,
    from_user_id       UUID        NOT NULL,
    to_user_id         UUID        NOT NULL,
    cheer_date         DATE        NOT NULL,
    kind               VARCHAR(20) NOT NULL,
    tap_count_snapshot BIGINT      NOT NULL,
    read_at            TIMESTAMPTZ,
    reward_shards      INTEGER,
    created_at         TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_cheer_public_id UNIQUE (public_id),
    CONSTRAINT uq_cheer_from_date_to UNIQUE (from_user_id, cheer_date, to_user_id)
);

-- 안 읽은 응원 조회와, 확인한 날 기준 하루 상한 계산에 쓴다.
CREATE INDEX IF NOT EXISTS ix_cheer_to_read ON cheer (to_user_id, read_at);

COMMIT;
